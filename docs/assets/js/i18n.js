function detect() {
  try {
    const saved = localStorage.getItem(KEY);
    if (LANGS.includes(saved)) return saved;
  } catch { /* ignore */ }
  const nav = (navigator.languages || [navigator.language || ""]).join(",").toLowerCase();
  return /\bzh/.test(nav) ? "zh-Hant" : "en";
}

let current = detect();
document.documentElement.lang = current;

export const lang = () => current;

export function setLang(next) {
  if (!LANGS.includes(next)) return;
  current = next;
  document.documentElement.lang = next;
  try { localStorage.setItem(KEY, next); } catch { /* ignore */ }
}

/** UI string lookup with {var} substitution. Falls back to zh-Hant, then the key. */
export function t(key, vars = {}) {
  const s = DICT[current][key] ?? DICT["zh-Hant"][key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? `{${k}}`));
}

/** Pick the current language from a localized {"zh-Hant": ..., "en": ...} value. */
export function loc(value) {
  if (value == null) return "";
  if (typeof value !== "object" || Array.isArray(value)) return value;
  return value[current] ?? value["zh-Hant"] ?? Object.values(value)[0] ?? "";
}

export const isZh = () => current === "zh-Hant";
